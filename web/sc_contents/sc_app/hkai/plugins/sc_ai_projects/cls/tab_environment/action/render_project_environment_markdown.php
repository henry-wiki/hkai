<?php

namespace sc\app\hkai\plugins\sc_ai_projects\tab_environment\action;

// == sc_ai_projects tab_environment render_project_environment_markdown：tab_environment 域動作（trait——掛入 tab_environment_Class；檔＝動作） ==
// == 職責：把專案級偵測結果渲染成 Markdown（純渲染，零偵測、零寫檔；系統級事實唔喺度重複——另有系統環境） ==

trait render_project_environment_markdown
{
    // 渲染主體（回傳完整 Markdown 字串；輸入＝專案偵測結果（Python 掃描專案目錄））
    public function render_project_environment_markdown($project_env_data)
    {
        $output_lines   = [];
        $output_lines[] = "<!-- AUTO-GENERATED by hkai — project environment (auto-detected). Do not edit. Regenerate via Project > 環境 ENV > 更新. -->";
        $output_lines[] = "<!-- Scope: project only (Python scan of the project directory). System-level facts are kept in the system environment — not duplicated here. -->";
        $output_lines[] = "";
        $output_lines[] = "## Project Environment (auto-detected)";
        $output_lines[] = "";

        // ── 基本（起碼要有——專案完整路徑＋名） ──
        $project_root = $project_env_data["root"];
        $project_name = $project_env_data["name"];

        // 顯示路徑（統一 "/"——G:/ 樣）
        $display_root = str_replace("\\", "/", $project_root);

        $output_lines[] = "- Root: {$display_root}";
        $output_lines[] = "- Name: {$project_name}";

        // ── VCS（git repo 先顯示——branch＋未提交提示） ──
        $vcs = $project_env_data["vcs"];
        if ($vcs !== null) {
            $vcs_type   = $vcs["type"];
            $vcs_branch = $vcs["branch"];
            $vcs_dirty  = $vcs["dirty"];

            $vcs_status = $vcs_branch;

            // 判定：有未提交變更 → 附加提示（同文章格式）
            if ($vcs_dirty === true) {
                $vcs_status = $vcs_branch . ", uncommitted changes";
            }

            $output_lines[] = "- VCS: {$vcs_type} (branch: {$vcs_status})";
        }

        // ── AGENTS.md（存在／未搵到——二選一顯式分支） ──
        $has_agents_md = $project_env_data["has_agents_md"];
        if ($has_agents_md === true) {
            $output_lines[] = "- AGENTS.md: exists";
        } else {
            $output_lines[] = "- AGENTS.md: not found";
        }

        // ── Languages（主要語言——偵測到先顯示） ──
        $languages = $project_env_data["languages"];
        if (count($languages) > 0) {
            $language_texts = [];

            // 逐語言組「名 百分比%」文字
            foreach ($languages as $language_item) {
                $language_name    = $language_item["name"];
                $language_percent = $language_item["percent"];
                $language_texts[] = "{$language_name} {$language_percent}%";
            }

            $languages_line = implode(", ", $language_texts);
            $output_lines[] = "- Languages: {$languages_line}";
        }

        // ── Frameworks（偵測到先顯示） ──
        $frameworks = $project_env_data["frameworks"];
        if (count($frameworks) > 0) {
            $frameworks_line = implode(", ", $frameworks);
            $output_lines[] = "- Frameworks: {$frameworks_line}";
        }

        // ── Build Systems（偵測到先顯示） ──
        $build_systems = $project_env_data["build_systems"];
        if (count($build_systems) > 0) {
            $build_systems_line = implode(", ", $build_systems);
            $output_lines[] = "- Build Systems: {$build_systems_line}";
        }

        // ── Package Managers（偵測到先顯示） ──
        $package_managers = $project_env_data["package_managers"];
        if (count($package_managers) > 0) {
            $package_managers_line = implode(", ", $package_managers);
            $output_lines[] = "- Package Managers: {$package_managers_line}";
        }

        // ── Test Tools（偵測到先顯示） ──
        $test_tools = $project_env_data["test_tools"];
        if (count($test_tools) > 0) {
            $test_tools_line = implode(", ", $test_tools);
            $output_lines[] = "- Test Tools: {$test_tools_line}";
        }

        // ── Linters（偵測到先顯示） ──
        $linters = $project_env_data["linters"];
        if (count($linters) > 0) {
            $linters_line = implode(", ", $linters);
            $output_lines[] = "- Linters: {$linters_line}";
        }

        // ── Required Runtimes（專案要求版本——偵測到先顯示） ──
        $required_runtimes = $project_env_data["required_runtimes"];
        if (count($required_runtimes) > 0) {
            $runtime_texts = [];

            // 逐 runtime 組「名 版本」文字
            foreach ($required_runtimes as $runtime_name => $runtime_version) {
                $runtime_texts[] = "{$runtime_name} {$runtime_version}";
            }

            $required_runtimes_line = implode(", ", $runtime_texts);
            $output_lines[] = "- Required Runtimes: {$required_runtimes_line}";
        }

        // ── Manifests（語言／生態標記——偵測到先顯示） ──
        $manifests = $project_env_data["manifests"];
        if (count($manifests) > 0) {
            $manifests_line = implode(", ", $manifests);
            $output_lines[] = "- Manifests: {$manifests_line}";
        }

        // ── Docker（有標記先顯示——Dockerfile／docker-compose） ──
        $docker_markers = [];

        // 判定：Dockerfile 存在 → 列
        if ($project_env_data["has_dockerfile"] === true) {
            $docker_markers[] = "Dockerfile";
        }

        // 判定：docker-compose 存在 → 列
        if ($project_env_data["has_docker_compose"] === true) {
            $docker_markers[] = "docker-compose";
        }

        // 判定：有任一標記 → 出一行
        if (count($docker_markers) > 0) {
            $docker_line   = implode(", ", $docker_markers);
            $output_lines[] = "- Docker: {$docker_line}";
        }

        // ── CI/CD（偵測到先顯示） ──
        $ci_cd = $project_env_data["ci_cd"];
        if (count($ci_cd) > 0) {
            $ci_cd_line    = implode(", ", $ci_cd);
            $output_lines[] = "- CI/CD: {$ci_cd_line}";
        }

        $detected_at = $project_env_data["detected_at"];

        $output_lines[] = "";
        $output_lines[] = "- Detected at: {$detected_at}";

        return implode("\r\n", $output_lines);
    }
}
