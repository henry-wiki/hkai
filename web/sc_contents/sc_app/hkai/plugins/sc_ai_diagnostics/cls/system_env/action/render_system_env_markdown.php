<?php

namespace sc\app\hkai\plugins\sc_ai_diagnostics\system_env\action;

// == sc_ai_diagnostics system_env render_system_env_markdown：system_env 域動作（trait——掛入 system_env_Class；檔＝動作） ==
// == 職責：把系統級環境 JSON 渲染成 Markdown（發去 AI 的環境段——純渲染，零偵測、零寫檔） ==

trait render_system_env_markdown
{
    // 渲染主體（回傳完整 Markdown 字串；輸入＝run_system_env_fetch 的統一結果）
    public function render_system_env_markdown($env_data)
    {
        $output_lines   = [];
        $output_lines[] = "<!-- AUTO-GENERATED by hkai diagnostics — system environment (auto-detected). Do not edit. Regenerate via Settings > Instructions > Environment. -->";
        $output_lines[] = "";
        $output_lines[] = "## System Environment (auto-detected)";
        $output_lines[] = "";
        $output_lines[] = "These facts were detected from the actual machine by the diagnostics service.";
        $output_lines[] = "If other instructions contradict these facts, trust the values below.";
        $output_lines[] = "";

        // ── OS 段 ──
        $os        = $env_data["os"];
        $os_name   = $os["name"];
        $os_release = $os["release"];
        $os_arch   = $os["arch"];
        $hostname  = $os["hostname"];

        $output_lines[] = "- OS: {$os_name} {$os_release} ({$os_arch})";
        $output_lines[] = "- Hostname: {$hostname}";

        // ── hardware 段（CPU 核心／記憶體——psutil 缺＝空 dict，整段唔放） ──
        $hardware = $env_data["hardware"];
        if (count($hardware) > 0) {
            $cpu_cores           = $hardware["cpu_cores"];
            $memory_total_gb     = $hardware["memory_total_gb"];
            $memory_available_gb = $hardware["memory_available_gb"];

            $output_lines[] = "- CPU cores: {$cpu_cores}";
            $output_lines[] = "- Memory: {$memory_total_gb} GB total ({$memory_available_gb} GB available)";
        }

        // ── disk 段（當前工作碟空間——失敗＝null，唔放） ──
        $disk = $env_data["disk"];
        if ($disk !== null) {
            $disk_mount    = $disk["mount"];
            $disk_free_gb  = $disk["free_gb"];
            $disk_total_gb = $disk["total_gb"];

            $output_lines[] = "- Disk ({$disk_mount}): {$disk_free_gb} GB free / {$disk_total_gb} GB";
        }

        // ── network 段（有外網／無外網——二選一顯式分支） ──
        $network = $env_data["network"];
        if ($network["internet"] === true) {
            $output_lines[] = "- Network: internet reachable";
        } else {
            $output_lines[] = "- Network: no internet";
        }

        // ── container 段（喺容器內先顯示——其餘唔放） ──
        $container = $env_data["container"];
        if ($container === true) {
            $output_lines[] = "- Container: running inside a container";
        }

        // ── shell／timezone／python（頂層欄位） ──
        $shell          = $env_data["shell"];
        $timezone       = $env_data["timezone"];
        $python_version = $env_data["python_version"];
        $detected_at    = $env_data["detected_at"];

        $output_lines[] = "- Shell: {$shell}";
        $output_lines[] = "- Timezone: {$timezone}";
        $output_lines[] = "- Python: {$python_version}";

        // ── runtimes 段（名稱 → 版本；只列偵測到的） ──
        $runtimes = $env_data["runtimes"];
        if (count($runtimes) > 0) {
            $runtime_texts = [];

            // 逐 runtime 組「名稱 版本」文字
            foreach ($runtimes as $runtime_name => $runtime_version) {
                $runtime_texts[] = "{$runtime_name} {$runtime_version}";
            }

            $runtime_line = implode(", ", $runtime_texts);
            $output_lines[] = "- Runtimes: {$runtime_line}";
        }

        // ── tools 段（分類 → 命令清單；只列偵測到的） ──
        $tools = $env_data["tools"];
        if (count($tools) > 0) {

            // 逐分類組「分類: a, b, c」一行
            foreach ($tools as $tool_category => $tool_names) {
                $tool_text  = implode(", ", $tool_names);
                $tool_label = str_replace("_", " ", $tool_category);
                $output_lines[] = "- {$tool_label}: {$tool_text}";
            }
        }

        $output_lines[] = "";
        $output_lines[] = "- Detected at: {$detected_at}";

        return implode("\r\n", $output_lines);
    }
}
